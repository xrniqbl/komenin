/**
 * Generate a Prisma baseline migration SQL from the current schema.
 *
 * Usage (from repo root):
 *   node scripts/generate-prisma-baseline.mjs
 *
 * Then for an existing DB that already matches schema:
 *   npx prisma migrate resolve --applied 0_init
 *
 * For empty DBs:
 *   npm run db:migrate:deploy
 */
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "prisma", "migrations", "0_init");
const outFile = join(outDir, "migration.sql");

mkdirSync(outDir, { recursive: true });

const result = spawnSync(
  "npx",
  [
    "prisma",
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema-datamodel",
    "prisma/schema.prisma",
    "--script",
  ],
  {
    cwd: root,
    encoding: "utf8",
    shell: true,
  },
);

if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "prisma migrate diff failed");
  process.exit(result.status || 1);
}

const sql = (result.stdout || "").trim();
if (!sql || sql.length < 20) {
  console.error("Unexpected empty SQL from prisma migrate diff");
  process.exit(1);
}

const header = `-- Baseline migration generated from prisma/schema.prisma
-- Generated by scripts/generate-prisma-baseline.mjs
-- Review before applying to production.

`;

writeFileSync(outFile, `${header}${sql}\n`, "utf8");
console.log(`Wrote ${outFile}`);
console.log(`Bytes: ${Buffer.byteLength(sql, "utf8")}`);
if (!existsSync(join(root, "prisma", "MIGRATIONS.md"))) {
  console.log("See prisma/MIGRATIONS.md for apply instructions.");
}
